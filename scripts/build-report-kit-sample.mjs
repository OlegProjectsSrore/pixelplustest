// Copies the owner-approved report sample with its LLM comments (PixelPlus_Report_Kit/PixelPlus_Audit_LLM_final.md)
// into the Worker as a string module for the report writer's instructions.
// Usage: node scripts/build-report-kit-sample.mjs "<path to PixelPlus_Audit_LLM_final.md>"
import fs from 'node:fs';

const source = process.argv[2];
if (!source) throw new Error('Pass the path to PixelPlus_Audit_LLM_final.md');
const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n').trim();
const target = new URL('../worker/src/report/report-kit-sample.ts', import.meta.url);
fs.writeFileSync(target, `// Generated by scripts/build-report-kit-sample.mjs from the approved PixelPlus_Report_Kit/PixelPlus_Audit_LLM_final.md. Do not edit by hand.
export const REPORT_KIT_SAMPLE = ${JSON.stringify(text)};
`);
console.log(`report-kit-sample.ts: ${text.length} characters`);
