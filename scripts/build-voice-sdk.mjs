import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { readFile, mkdir, writeFile } from 'node:fs/promises';

const require = createRequire(new URL('../worker/package.json', import.meta.url));
const { build } = require('esbuild');
const root = fileURLToPath(new URL('../worker/', import.meta.url));
const output = fileURLToPath(new URL('../dist/assets/ultravox-sdk.js', import.meta.url));
const sdk = JSON.parse(await readFile(require.resolve('ultravox-client/package.json'), 'utf8'));
const result = await build({
  absWorkingDir: root,
  stdin: { contents: "export { UltravoxSession } from 'ultravox-client';", resolveDir: root, sourcefile: 'voice-sdk-entry.js' },
  bundle: true, platform: 'browser', format: 'esm', target: 'es2022', minify: true,
  outfile: output, metafile: true, legalComments: 'eof',
  banner: { js: `// Generated by scripts/build-voice-sdk.mjs; ultravox-client ${sdk.version}.` },
});
const emitted = Object.values(result.metafile.outputs).find(item => item.exports.includes('UltravoxSession'));
if (!emitted || emitted.imports.some(item => item.external)) throw new Error('SDK must export UltravoxSession with no external runtime imports');
const artifacts = new URL('../.artifacts/', import.meta.url);
await mkdir(artifacts, { recursive: true });
await writeFile(new URL('voice-sdk-metafile.json', artifacts), JSON.stringify(result.metafile, null, 2));
console.log(`ultravox-client ${sdk.version}: ${emitted.bytes} bytes; standalone ESM: ${output}`);
